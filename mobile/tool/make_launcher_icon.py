#!/usr/bin/env python3
"""Makes the HaoTranNAS launcher icon: two NAS drive bays and a check mark,
white on deep blue.

Author: Hao Tran

One shape, two outputs, so they always match:
  - Android 8+ (API 26+): adaptive icon = vector foreground + background color
    (+ monochrome layer for Android 13 themed icons).
  - Android 7 (API 24-25): PNG files in every mipmap density.

Usage (from mobile/):  python3 tool/make_launcher_icon.py
Needs Pillow (PIL). Writes into android/app/src/main/res/.

Coordinates are in the adaptive-icon canvas: 108 x 108 units. The launcher
mask can cut everything outside the circle of radius 33 around the center
(54, 54), so the whole shape stays inside it.
"""

from pathlib import Path

from PIL import Image, ImageDraw

BACKGROUND_COLOR = "#1F4E9C"  # deep blue
SHAPE_COLOR = "#FFFFFF"
CANVAS_UNITS = 108
LEGACY_VISIBLE_START = 18  # legacy icons show the 72-unit middle, like adaptive ones
LEGACY_VISIBLE_UNITS = 72

# Drive bays: (left, top, right, bottom, corner radius).
DRIVE_BAYS = [(34, 31, 74, 46, 4), (34, 50, 74, 65, 4)]
SLOT_LEFT, SLOT_RIGHT, SLOT_HEIGHT, SLOT_RADIUS = 39, 55, 4, 2
LIGHT_CENTER_X, LIGHT_RADIUS = 67, 2.5
# Check mark under the drives: a round-capped polyline.
CHECK_POINTS = [(46, 72.5), (51.5, 78), (62, 69.5)]
CHECK_STROKE_WIDTH = 5

RESOURCE_FOLDER = Path(__file__).resolve().parent.parent / "android/app/src/main/res"
LEGACY_SIZES_PX = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def rounded_rect_path(left, top, right, bottom, radius):
    """SVG/Android path data for a rounded rectangle, clockwise."""
    return (
        f"M{left + radius},{top} H{right - radius} "
        f"A{radius},{radius} 0 0 1 {right},{top + radius} V{bottom - radius} "
        f"A{radius},{radius} 0 0 1 {right - radius},{bottom} H{left + radius} "
        f"A{radius},{radius} 0 0 1 {left},{bottom - radius} V{top + radius} "
        f"A{radius},{radius} 0 0 1 {left + radius},{top} Z"
    )


def circle_path(center_x, center_y, radius):
    return (
        f"M{center_x - radius},{center_y} "
        f"A{radius},{radius} 0 1 0 {center_x + radius},{center_y} "
        f"A{radius},{radius} 0 1 0 {center_x - radius},{center_y} Z"
    )


def slot_box(bay):
    _, top, _, bottom, _ = bay
    middle_y = (top + bottom) / 2
    return (SLOT_LEFT, middle_y - SLOT_HEIGHT / 2, SLOT_RIGHT, middle_y + SLOT_HEIGHT / 2)


def light_center(bay):
    _, top, _, bottom, _ = bay
    return (LIGHT_CENTER_X, (top + bottom) / 2)


def foreground_vector_xml():
    """Vector drawable: each bay is one even-odd path, so the slot and the
    light are real holes (needed for the one-color themed icon)."""
    paths = []
    for bay in DRIVE_BAYS:
        slot_left, slot_top, slot_right, slot_bottom = slot_box(bay)
        light_x, light_y = light_center(bay)
        path_data = " ".join(
            [
                rounded_rect_path(*bay),
                rounded_rect_path(slot_left, slot_top, slot_right, slot_bottom, SLOT_RADIUS),
                circle_path(light_x, light_y, LIGHT_RADIUS),
            ]
        )
        paths.append(
            f'    <path\n        android:fillColor="{SHAPE_COLOR}"\n'
            f'        android:fillType="evenOdd"\n        android:pathData="{path_data}" />'
        )
    check_data = "M{},{} L{},{} L{},{}".format(*[value for point in CHECK_POINTS for value in point])
    paths.append(
        f'    <path\n        android:fillColor="#00000000"\n'
        f'        android:strokeColor="{SHAPE_COLOR}"\n'
        f'        android:strokeWidth="{CHECK_STROKE_WIDTH}"\n'
        f'        android:strokeLineCap="round"\n        android:strokeLineJoin="round"\n'
        f'        android:pathData="{check_data}" />'
    )
    return (
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        "<!-- Generated by tool/make_launcher_icon.py. Edit the script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{CANVAS_UNITS}dp"\n    android:height="{CANVAS_UNITS}dp"\n'
        f'    android:viewportWidth="{CANVAS_UNITS}"\n    android:viewportHeight="{CANVAS_UNITS}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


ADAPTIVE_ICON_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_launcher_icon.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND_COLOR_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_launcher_icon.py. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND_COLOR}</color>
</resources>
"""


def draw_icon_png(size_px, oversample=8):
    """Legacy square icon with rounded corners: the 72-unit middle of the canvas."""
    work_px = size_px * oversample
    scale = work_px / LEGACY_VISIBLE_UNITS

    def to_px(value):
        return (value - LEGACY_VISIBLE_START) * scale

    image = Image.new("RGBA", (work_px, work_px), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((0, 0, work_px - 1, work_px - 1), radius=work_px * 0.18, fill=BACKGROUND_COLOR)
    for bay in DRIVE_BAYS:
        left, top, right, bottom, radius = bay
        draw.rounded_rectangle((to_px(left), to_px(top), to_px(right), to_px(bottom)), radius=radius * scale, fill=SHAPE_COLOR)
        slot_left, slot_top, slot_right, slot_bottom = slot_box(bay)
        draw.rounded_rectangle(
            (to_px(slot_left), to_px(slot_top), to_px(slot_right), to_px(slot_bottom)),
            radius=SLOT_RADIUS * scale,
            fill=BACKGROUND_COLOR,
        )
        light_x, light_y = light_center(bay)
        light_radius_px = LIGHT_RADIUS * scale
        draw.ellipse(
            (to_px(light_x) - light_radius_px, to_px(light_y) - light_radius_px,
             to_px(light_x) + light_radius_px, to_px(light_y) + light_radius_px),
            fill=BACKGROUND_COLOR,
        )
    check_px = [(to_px(x_units), to_px(y_units)) for x_units, y_units in CHECK_POINTS]
    stroke_px = CHECK_STROKE_WIDTH * scale
    draw.line(check_px, fill=SHAPE_COLOR, width=round(stroke_px), joint="curve")
    for point_x, point_y in (check_px[0], check_px[-1]):  # round caps
        draw.ellipse((point_x - stroke_px / 2, point_y - stroke_px / 2, point_x + stroke_px / 2, point_y + stroke_px / 2), fill=SHAPE_COLOR)
    return image.resize((size_px, size_px), Image.LANCZOS)


def main():
    (RESOURCE_FOLDER / "drawable/ic_launcher_foreground.xml").write_text(foreground_vector_xml())
    adaptive_folder = RESOURCE_FOLDER / "mipmap-anydpi-v26"
    adaptive_folder.mkdir(exist_ok=True)
    (adaptive_folder / "ic_launcher.xml").write_text(ADAPTIVE_ICON_XML)
    (RESOURCE_FOLDER / "values/ic_launcher_background.xml").write_text(BACKGROUND_COLOR_XML)
    for density, size_px in LEGACY_SIZES_PX.items():
        draw_icon_png(size_px).save(RESOURCE_FOLDER / f"mipmap-{density}/ic_launcher.png", optimize=True)
    print("launcher icon written to", RESOURCE_FOLDER)


if __name__ == "__main__":
    main()
